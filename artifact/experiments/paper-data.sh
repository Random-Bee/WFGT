#!/usr/bin/env bash
set -euo pipefail

# The two-socket times of the paper's Section 8, as LaTeX, from
# $RESULTS_DIR/$RESULTS.csv and, for the graph of hubs, $HUBS.csv: by default
# results/final-single.csv and results/hubs-single.csv, the paper's, and with
# RESULTS_DIR=../benchmark/results a new run of benchmark.sh. For each graph a
# table of the median
# time per search in ms at each thread count, over the builds that ran
# correctly (a rerun build's latest time), for each program, followed by the
# distances to the fastest and slowest build for error bars, nan where no build
# has the point, and no row for a thread count that no program ran; and the
# sequential baseline's median as \seqGraph:
#   ./paper-data.sh > ../paper/sections/data.tex

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
root=$(cd "$here/.." && pwd)
results=${RESULTS_DIR:-$root/results}
csv="$results/${RESULTS:-final-single}.csv"
hubs="$results/${HUBS:-hubs-single}.csv"
for file in "$csv" "$hubs"; do
    [ -f "$file" ] || { echo "missing $file" >&2; exit 1; }
done

echo "% generated by artifact/experiments/paper-data.sh from $(basename "$csv") and $(basename "$hubs"): median ms per search over five builds on two sockets, then minus/plus ranges, nan where a point is missing"
awk -F, '
    function med(s,   v, k) { k = split(s, v, " "); asort(v); return (k % 2) ? v[(k + 1) / 2] : (v[k / 2] + v[k / 2 + 1]) / 2 }
    NR > 1 && $1 == "both" && $7 == "yes" && $6 ~ /^[0-9]+$/ { last[$2 SUBSEP $3 SUBSEP $5 SUBSEP $4] = $6 }
    END {
        for (k in last) { split(k, p, SUBSEP); key = p[1] SUBSEP p[2] SUBSEP p[3]; t[key] = t[key] " " last[k] }
        split("lj twitter road uk kron hubs", graphs, " ")
        split("LJ Twitter Road UK Kron Hubs", names, " ")
        split("1 2 4 8 16 24 32 40 48 56 64 80 96 112 128", counts, " ")
        split("wd mem gapbs gbbs pasgal", progs, " ")
        for (g = 1; g <= 6; g++) {
            printf "\\pgfplotstableread{\nt wd wdminus wdplus mem memminus memplus gapbs gapbsminus gapbsplus gbbs gbbsminus gbbsplus pasgal pasgalminus pasgalplus\n"
            for (c = 1; c <= 15; c++) {
                row = counts[c]; ran = 0
                for (j = 1; j <= 5; j++) {
                    key = graphs[g] SUBSEP counts[c] SUBSEP progs[j]
                    if (key in t) {
                        k = split(t[key], v, " "); asort(v); m = med(t[key])
                        row = row sprintf(" %.1f %.1f %.1f", m / 1000, (m - v[1]) / 1000, (v[k] - m) / 1000)
                        ran = 1
                    }
                    else row = row " nan nan nan"
                }
                if (ran) print row
            }
            printf "}\\dataTwo%s\n", names[g]
            key = graphs[g] SUBSEP 1 SUBSEP "seq"
            printf "\\newcommand{\\seq%s}{%s}\n", names[g], (key in t) ? sprintf("%.1f", med(t[key]) / 1000) : "nan"
        }
    }' "$csv" "$hubs"
