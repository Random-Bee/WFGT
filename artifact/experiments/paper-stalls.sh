#!/usr/bin/env bash
set -euo pipefail

# The data of the stall experiments for the paper, from the summaries of
# stalls/stalls.sh and stalls/noise.sh and the runs of helping/help-stalls.sh,
# as pgfplots tables, in ms per search unless named otherwise. For each graph of GRAPHS
# (all six by default), with <G> its name in the tables (LiveJournal, Twitter,
# Road, Uk, Kron or Hubs):
#   \dataStallLength<G>  one thread stalled per level or round, by the length
#                        of its stall in us; wdlast and memlast are when the
#                        last thread of our programs returned
#   \dataNoiseLength<G>  every thread stalled at random for 2% of its time, by
#                        the length of a stall in us, 0 being the runs without
#                        stalls
#   \dataNoiseShare<G>   every thread stalled at random in stalls of 1 ms, by
#                        the percent of its time stalled, 0 being the runs
#                        without stalls
#   \dataStallPoints<G>  our programs stalled after a winning CAS or in a hub,
#                        by the length of a stall in us
# leaving out the settings that a graph was not run with; and from the runs on
# LiveJournal:
#   \dataHelpWork     the work of helpers in the counting build, in percent: of
#                     the vertices, neighbors and blocks of all owners, of the
#                     blocks of the stalled owner, and the neighbors and blocks
#                     done again; each the median over the runs of its share
#                     in a run, so that a share's parts come from one run
# The files are read from RESULTS, by default the paper's in results/, and the
# runs of help-stalls.sh can be given as HELP_RUNS:
#   ./paper-stalls.sh > ../paper/sections/data-stalls.tex

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
root=$(cd "$here/.." && pwd)
results=${RESULTS:-$root/results}
read -r -a graphs <<< "${GRAPHS:-lj twitter road uk kron hubs}"
help_runs=${HELP_RUNS:-$results/help-stalls-both.csv}

table_name() {
    case $1 in
        lj) echo LiveJournal ;;
        twitter) echo Twitter ;;
        road) echo Road ;;
        uk) echo Uk ;;
        kron) echo Kron ;;
        hubs) echo Hubs ;;
        *) return 1 ;;
    esac
}

# LiveJournal keeps the names of the runs on both sockets
summary() {
    if [ "$2" = lj ]; then
        echo "$results/$1-both-summary.csv"
    else
        echo "$results/$1-$2-summary.csv"
    fi
}

for graph in "${graphs[@]}"; do
    table_name "$graph" > /dev/null || { echo "unknown graph $graph" >&2; exit 1; }
    for file in "$(summary stalls "$graph")" "$(summary noise "$graph")"; do
        [ -f "$file" ] || { echo "missing $file" >&2; exit 1; }
    done
done
[ -f "$help_runs" ] || { echo "missing $help_runs" >&2; exit 1; }

echo "% generated by artifact/experiments/paper-stalls.sh from the stall and noise summaries of ${graphs[*]}, and $(basename "$help_runs")"

for graph in "${graphs[@]}"; do
    name=$(table_name "$graph")

    # experiment,stalled,stall_us,program,median_us,min_us,max_us,median_last_us,runs
    awk -F, -v name="$name" '
        NR > 1 && $1 == "length" && $2 == 1 { t[$3, $4] = $5; l[$3, $4] = $8; us[$3] = 1 }
        function ms(v) { return v == "" ? "nan" : sprintf("%.1f", v / 1000) }
        END {
            n = asorti(us, keys, "@ind_num_asc")
            print "\\pgfplotstableread{"
            print "us wd mem gapbs gbbs pasgal wdlast memlast"
            for (i = 1; i <= n; i++) {
                u = keys[i]
                printf "%s %s %s %s %s %s %s %s\n", u, ms(t[u, "wd"]), ms(t[u, "mem"]), ms(t[u, "gapbs"]),
                       ms(t[u, "gbbs"]), ms(t[u, "pasgal"]), ms(l[u, "wd"]), ms(l[u, "mem"])
            }
            print "}\\dataStallLength" name
        }' "$(summary stalls "$graph")"

    # experiment,stall_us,share_permille,program,median_us,min_us,max_us,median_last_us,runs
    awk -F, -v name="$name" '
        NR > 1 { t[$1, $2, $3, $4] = $5 }
        function ms(v) { return v == "" ? "nan" : sprintf("%.1f", v / 1000) }
        function row(x, e, u, s) {
            if (!((e, u, s, "wd") in t)) return
            printf "%s %s %s %s %s %s\n", x, ms(t[e, u, s, "wd"]), ms(t[e, u, s, "mem"]),
                   ms(t[e, u, s, "gapbs"]), ms(t[e, u, s, "gbbs"]), ms(t[e, u, s, "pasgal"])
        }
        END {
            print "\\pgfplotstableread{"
            print "us wd mem gapbs gbbs pasgal"
            row(0, "none", 0, 0)
            split("10 100 1000 10000", lengths, " ")
            for (i = 1; i <= 4; i++) row(lengths[i], "length", lengths[i], 20)
            print "}\\dataNoiseLength" name
            print "\\pgfplotstableread{"
            print "share wd mem gapbs gbbs pasgal"
            row(0, "none", 0, 0)
            split("5 10 20 50 100 200 500", shares, " ")
            for (i = 1; i <= 7; i++) {
                s = shares[i]
                if (s == 20) row(s / 10, "length", 1000, 20)
                else row(s / 10, "share", 1000, s)
            }
            print "}\\dataNoiseShare" name
            print "\\pgfplotstableread{"
            print "us wdcas memcas wdhub memhub"
            split("0 10 100 1000 10000", points, " ")
            for (i = 1; i <= 5; i++) {
                u = points[i]
                if (!(("cas", u, 20, "wd") in t)) continue
                printf "%s %s %s %s %s\n", u, ms(t["cas", u, 20, "wd"]), ms(t["cas", u, 20, "mem"]),
                       ms(t["hub", u, 20, "wd"]), ms(t["hub", u, 20, "mem"])
            }
            print "}\\dataStallPoints" name
        }' "$(summary noise "$graph")"
done

# the runs: stall_us,run,program,us,last_us,correct,v00,v01,v10,v11,e00,e01,
# e10,e11,b00,b01,b10,b11,repeated,bu_levels,blocks,repeated_edges,finished
awk -F, '
    FNR > 1 && $3 == "count" && $6 == "yes" {
        v = $7 + $8 + $9 + $10; e = $11 + $12 + $13 + $14; b = $15 + $16 + $17 + $18
        if (v == 0 || e == 0 || b == 0) next
        k = ++runs[$1]
        share[$1, 1, k] = 100 * ($8 + $10) / v
        share[$1, 2, k] = 100 * ($12 + $14) / e
        share[$1, 3, k] = 100 * ($16 + $18) / b
        share[$1, 4, k] = $17 + $18 > 0 ? 100 * $18 / ($17 + $18) : 0
        share[$1, 5, k] = 100 * $22 / e
        share[$1, 6, k] = 100 * (b - $20 * $21) / b
    }
    function median(u, s,   a, i, n) {
        n = runs[u]
        for (i = 1; i <= n; i++) a[i] = share[u, s, i]
        asort(a)
        return sprintf("%.1f", n % 2 ? a[(n + 1) / 2] : (a[n / 2] + a[n / 2 + 1]) / 2)
    }
    END {
        n = asorti(runs, keys, "@ind_num_asc")
        print "\\pgfplotstableread{"
        print "us vertices neighbors blocks stalled repneighbors repblocks"
        for (i = 1; i <= n; i++) {
            u = keys[i]
            printf "%s %s %s %s %s %s %s\n", u, median(u, 1), median(u, 2), median(u, 3),
                   median(u, 4), median(u, 5), median(u, 6)
        }
        print "}\\dataHelpWork"
    }' "$help_runs"
